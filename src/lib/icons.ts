export type IconName = keyof typeof ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

export const iconFor = (name?: string | null, fallback: LucideIcon = Check): LucideIcon =>
  (name && ICONS[name as IconName]) || fallback;
